"""Export the API contract used by the frontend, generated from backend code:

  backend/openapi.json                  OpenAPI spec  -> frontend TypeScript types (npm run gen:api)
  frontend/src/api/constraints.json     Allowed parameter values/limits for the form controls

Both files are committed. tests/test_contract.py fails if they are out of date, so the
frontend can never silently drift from the backend's real validation rules.

Usage (from backend/):  .venv/bin/python scripts/export_contract.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from app.core.config import REPO_ROOT, Settings  # noqa: E402
from app.jobs.images import ALLOWED_FORMATS  # noqa: E402
from app.jobs.models import MAX_FRAMES, MIN_FRAMES, SUPPORTED_RESOLUTIONS, GenerationParams  # noqa: E402

OPENAPI_PATH = BACKEND / "openapi.json"
CONSTRAINTS_PATH = REPO_ROOT / "frontend" / "src" / "api" / "constraints.json"


def _bounds(field: str) -> dict:
    info = GenerationParams.model_fields[field]
    out: dict = {"default": info.default}
    for m in info.metadata:
        for attr, key in (("ge", "min"), ("le", "max")):
            if hasattr(m, attr):
                out[key] = getattr(m, attr)
    return out


def build_constraints() -> dict:
    defaults = Settings(_env_file=None)
    return {
        "_comment": "GENERATED by backend/scripts/export_contract.py. Do not edit by hand.",
        "resolutions": [{"value": k, "width": w, "height": h} for k, (w, h) in SUPPORTED_RESOLUTIONS.items()],
        "defaultResolution": GenerationParams.model_fields["resolution"].default,
        "numFrames": {"min": MIN_FRAMES, "max": MAX_FRAMES, "step": 4,
                      "default": GenerationParams.model_fields["num_frames"].default},
        "fps": _bounds("fps"),
        "steps": _bounds("steps"),
        "guidanceScale": _bounds("guidance_scale"),
        "seed": {"min": 0, "max": 2**32 - 1},
        "prompt": {"maxChars": defaults.max_prompt_chars},
        "image": {
            "mimeTypes": sorted(ALLOWED_FORMATS.values()),
            "maxBytes": defaults.max_upload_bytes,
            "minSide": defaults.min_image_side,
            "maxSide": defaults.max_image_side,
        },
    }


def build_openapi() -> dict:
    from app.main import create_app

    return create_app(Settings(_env_file=None)).openapi()


def dumps(obj: dict) -> str:
    return json.dumps(obj, indent=2, sort_keys=False) + "\n"


def main() -> None:
    OPENAPI_PATH.write_text(dumps(build_openapi()))
    CONSTRAINTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    CONSTRAINTS_PATH.write_text(dumps(build_constraints()))
    print(f"wrote {OPENAPI_PATH.relative_to(REPO_ROOT)} and {CONSTRAINTS_PATH.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
